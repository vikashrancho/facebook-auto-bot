import fs from "fs";
import path from "path";

const envLocalPath = path.resolve(".env.local");
if (fs.existsSync(envLocalPath)) {
  const content = fs.readFileSync(envLocalPath, "utf-8");
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (trimmed && !trimmed.startsWith("#") && trimmed.includes("=")) {
      const idx = trimmed.indexOf("=");
      const key = trimmed.slice(0, idx).trim();
      const val = trimmed.slice(idx + 1).trim();
      if (!process.env[key]) {
        process.env[key] = val;
      }
    }
  }
}

import { supabaseAdmin } from "../src/lib/supabase/server";

async function cleanup() {
  const db = supabaseAdmin();
  
  // Test titles generated by test-multi-page.ts
  const testTitles = [
    "Draft Stock 1",
    "Draft Jesus 1",
    "Draft Doggie 1",
    "Golden Retriever Daily Joy",
    "Grace and Peace for Your Day",
    "S&P 500 Market Close Analysis",
    "Ambiguous Dog Post",
    "Non Existent Page Post",
    "Conflicting Target Post",
    "AI in Trading",
    "Concurrent Post A",
    "Concurrent Post B",
    "Legacy Post",
    "Page Selection By Name",
    "Mismatch Title"
  ];

  console.log("Cleaning up test posts created by automated test suite...");

  const { data: found, error: findError } = await db
    .from("posts")
    .select("id, title, status, created_at")
    .in("title", testTitles);

  if (findError) {
    console.error("Error finding test posts:", findError);
    return;
  }

  console.log(`Found ${found?.length || 0} test posts to remove:`);
  for (const p of found || []) {
    console.log(`- Deleting: [${p.status}] ${p.id} "${p.title}" (${p.created_at})`);
  }

  if (found && found.length > 0) {
    const ids = found.map((p) => p.id);
    const { error: delError } = await db.from("posts").delete().in("id", ids);
    if (delError) {
      console.error("Delete error:", delError);
    } else {
      console.log(`Successfully deleted ${ids.length} test posts!`);
    }
  }

  // Also verify remaining queue
  const { data: remaining } = await db
    .from("posts")
    .select("id, title, status, page_name, created_at")
    .in("status", ["draft", "scheduled", "publishing"])
    .order("created_at", { ascending: false });

  console.log(`\nRemaining items in queue: ${remaining?.length || 0}`);
  for (const r of remaining || []) {
    console.log(`  [${r.status}] ${r.page_name || "Unassigned"} - "${r.title}" (${r.created_at})`);
  }
}

cleanup().catch(console.error);
